// The "what's similar" index (owner, 2026-10-21: "make them all easier to find"): every family skill (lib/skill-family.js, a `parts:`
// line in its file) with each part's examples, written to void-live-deploy/lib/similar-index.js for skills/similar.js, so a combined
// skill lists its modes and siblings wherever someone asks. Generated; never edited by hand.
//   node tools/similar-index.mjs           write it         node tools/similar-index.mjs --check   exit 1 when it is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..'), skills = resolve(root, 'void-live-deploy/skills');
export const FILE = resolve(root, 'void-live-deploy/lib/similar-index.js');
const src = (n) => { const f = resolve(skills, n + '.js'); return existsSync(f) ? readFileSync(f, 'utf8') : ''; };
/** the examples a skill file lists literally (the same reading functions/tools.json.js does). Pure. */
export function examplesOf(text) {
  const m = String(text).match(/examples\s*:\s*\[([^\]]*)\]/);
  return m ? Array.from(m[1].matchAll(/'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"/g)).map((x) => (x[1] ?? x[2]).replace(/\\'/g, "'")).slice(0, 6) : [];
}
export const partsOf = (text) => { const m = /^\s*\*\s*parts:\s*\[([^\]]*)\]/m.exec(String(text)); return m ? Array.from(m[1].matchAll(/'([a-z0-9-]+)'/g)).map((x) => x[1]) : null; };
export function build() {
  const index = JSON.parse(readFileSync(resolve(skills, 'index.json'), 'utf8')), out = {};
  for (const n of index) { const parts = partsOf(src(n)); if (parts) out[n] = parts.map((p) => ({ name: p, examples: examplesOf(src(p)) })); }
  return { note: 'Generated by tools/similar-index.mjs: each family skill and its parts (modes), for "what\'s similar". Do not edit by hand.', families: out };
}
const text = () => '// Generated by tools/similar-index.mjs (each family skill and its parts, for "what\'s similar"). Do not edit by hand.\nexport default ' + JSON.stringify(build(), null, 1) + ';\n';
if (import.meta.url === 'file://' + process.argv[1]) {
  if (process.argv.includes('--check')) { const ok = existsSync(FILE) && readFileSync(FILE, 'utf8') === text(); if (!ok) { console.error('lib/similar-index.js is stale: run node tools/similar-index.mjs'); process.exit(1); } console.log('lib/similar-index.js is current'); }
  else { writeFileSync(FILE, text()); console.log('wrote lib/similar-index.js: ' + Object.keys(build().families).length + ' families'); }
}
