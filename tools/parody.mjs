// The 30-game parody matrix (domains/void.board-game-law.md §5) as data for the game rack (asked by Void: "Integrate the 30-game
// matrix into a searchable 'Games' skill" and "a 'parody-forge' card ... instant Verse-branded game generation").
//   node tools/parody.mjs           write void-live-deploy/lib/parody.js from the doc
//   node tools/parody.mjs --check   exit 1 when it is stale (tools/void-asks-store.test.mjs checks it too)
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DOC = path.join(root, 'domains/void.board-game-law.md'), OUT = path.join(root, 'void-live-deploy/lib/parody.js');
const plain = (s) => String(s).replace(/\*\*/g, '').replace(/\s+/g, ' ').trim();
/** the matrix rows from the doc. Pure. */
export function rows(md) {
  const sec = String(md).split(/^## 5\. /m)[1] || ''; const out = [];
  for (const l of sec.split(/^## /m)[0].split('\n')) {
    const c = l.split('|').slice(1, -1).map((x) => x.trim());
    if (c.length !== 6 || c[0] === 'Game' || /^-+$/.test(c[0])) continue;
    const [game, status, mark, safe, generic, par] = c, [pname, twist] = plain(par).split(' · ');
    const names = plain(game).replace(/\([^)]*\)/g, '').split(/\s*[/,]\s*/).map((x) => x.trim().toLowerCase().replace(/[^a-z0-9 &']+/g, '').trim()).filter(Boolean);
    out.push({ game: plain(game), names, pd: /\bPD\b/.test(status) && !/^Protected$/i.test(plain(status)), status: plain(status), protects: plain(mark), safest: plain(safe), generic: plain(generic), parody: pname, twist: twist || '' });
  }
  return out;
}
export const source = (md) => '// generated by tools/parody.mjs from domains/void.board-game-law.md §5 (not legal advice). Do not edit.\nexport default ' + JSON.stringify(rows(md), null, 1) + ';\n';
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const s = source(fs.readFileSync(DOC, 'utf8'));
  if (process.argv.includes('--check')) { if (fs.readFileSync(OUT, 'utf8') !== s) { console.error('lib/parody.js is stale: node tools/parody.mjs'); process.exit(1); } }
  else { fs.writeFileSync(OUT, s); console.log('wrote lib/parody.js: ' + rows(fs.readFileSync(DOC, 'utf8')).length + ' games'); }
}
