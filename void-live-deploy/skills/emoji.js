export function isEmoji(text) {
  return /^(?:please\\s+)?(?:(?:give\\s+me\\s+|pick\\s+|show\\s+|random\\s+|a\\s+)?(?:\\d+\\s+)?(?:random\\s+)?emojis?|random\\s+emoji|pick\\s+an?\\s+emoji)$/i.test(String(text || '').trim().replace(/[?!.]+$/, ''));
}

function pick(n = 1) {
  const out = [];
  for (let i = 0; i < Math.min(10, Math.max(1, n)); i++) out.push(EMOJIS[Math.floor(Math.random() * EMOJIS.length)]);
  return out;
}

async function run(text, api) {
  const { showPage, esc } = api;
  const m = /(?:\\d+)/.exec(String(text || ''));
  const n = m ? Math.min(10, Math.max(1, +m[0])) : 1;
  const got = pick(n);
  showPage((p) => { p.innerHTML = '<h2>Random emoji</h2><p style="font-size:48px;line-height:1.2">' + got.join(' ') + '</p><div class="sub">say “another emoji” or “3 emojis” for more</div>'; });
  return 'emoji';
}

