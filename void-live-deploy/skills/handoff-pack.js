/**
 * handoff-pack skill — package status, docs and running automations for a client handoff.
 * Reduces client work by giving a clear, living package of "we own the heavy lifting".
 * "package the handoff for the client", "hand off status and automations", "client handoff pack".
 */
export function isHandoffPack(text) {
  return /^(?:please\s+)?(?:(?:package|make|show|open|generate)\s+(?:the\s+)?)?(?:client\s+)?handoff(?:\s+pack)?(?:\s+(?:for\s+the\s+client|status\s+and\s+automations))?$/i.test(String(text || '').trim().replace(/[?!.]+$/, ''));
}

function run(text, api) {
  const { showPage, esc } = api;
  const pack = {
    status: 'Systems running; heavy lifting owned by A-to-Mind.',
    automations: ['Watch for price changes (paused)', 'Daily status digest (active)', 'Proposal drafts on reply (active)'],
    docs: ['https://a-to-mind.com/fix/', 'Growth ledger at /growth'],
    next: 'Client reviews the pack; any yes goes through the confirm line.'
  };
  showPage((el) => {
    el.innerHTML = '<h2>Client handoff pack</h2>'
      + '<p><strong>Status:</strong> ' + esc(pack.status) + '</p>'
      + '<p><strong>Running automations:</strong></p><ul>' + pack.automations.map(a => '<li>' + esc(a) + '</li>').join('') + '</ul>'
      + '<p><strong>Docs:</strong> ' + pack.docs.map(d => '<a href="' + esc(d) + '">' + esc(d) + '</a>').join(', ') + '</p>'
      + '<p><strong>Next:</strong> ' + esc(pack.next) + '</p>'
      + '<button id="dl">Download .md pack</button><div class="sub">Packages the handoff so the client sees status, automations and docs without more work.</div>';
    el.querySelector('#dl').onclick = () => {
      const md = '# Client handoff pack\n\n**Status:** ' + pack.status + '\n\n**Automations:**\n' + pack.automations.map(a => '- ' + a).join('\n') + '\n\n**Docs:**\n' + pack.docs.map(d => '- ' + d).join('\n') + '\n\n**Next:** ' + pack.next + '\n\n_Generated by Verse for idea-to-system delivery._';
      const a = document.createElement('a');
      a.href = URL.createObjectURL(new Blob([md], { type: 'text/markdown' }));
      a.download = 'client-handoff-pack.md';
      a.click();
      setTimeout(() => URL.revokeObjectURL(a.href), 2000);
    };
  });
  return 'handoff-pack';
}

export default {
  name: 'handoff-pack',
  examples: [
    'package the handoff for the client',
    'hand off status and automations',
    'client handoff pack'
  ],
  nearMisses: [
    'my automations',
    'turn this into a proposal'
  ],
  match(lower) { return isHandoffPack(lower); },
  run
};
