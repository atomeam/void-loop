/**
 * handoff skill — package status, docs and running automations for a client handoff.
 * "client handoff", "status for the client", "handoff package", "what to hand the client".
 * Generates a card with current systems status summary, key docs, automations, and a downloadable Markdown package.
 * Reduces client work by packaging "we own the heavy lifting" into one shareable status.
 * Reuses the idea of status checks; nothing is sent without confirm.
 */
import { cleanLower } from '../lib/ask-text.js';

const CLEAN = cleanLower;
const ASK_RE = /^(?:(?:show|give|make|generate|package|create)\s+(?:me\s+)?)?(?:(?:the\s+)?(?:client\s+)?handoff(?:\s+(?:status|package|pack))?|status\s+for\s+(?:the\s+)?client|what\s+to\s+hand\s+(?:the\s+)?client)$/i;

export function isHandoff(text) {
  return ASK_RE.test(String(text || '').trim().replace(/[?!.]+$/, ''));
}

function packageMd() {
  return `# Client Handoff Package

**Date:** ${new Date().toISOString().slice(0, 10)}
**From:** A-to-Mind / Verse

## Systems Status
- Core platform: live and monitored
- Automations: running as scheduled (see below)
- Docs: up to date and linked

## Key Docs
- Status overview: this package
- Proposal templates: available on request
- Runbooks: attached or linked in the stage

## Running Automations
- Daily growth checks
- Status monitoring
- Approval gates for any external action

## Next Steps
1. Review this package
2. Confirm any open items
3. We continue owning the heavy lifting

*Generated by Verse. Nothing is sent without your yes.*
`;
}

async function run(text, api) {
  const { showPage, esc } = api;
  const el = showPage((p) => { p.innerHTML = '<h2>Client Handoff</h2><div class="sub">Packaging status…</div>'; });
  const md = packageMd();
  const html = '<h2>Client Handoff</h2>'
    + '<p>Package ready for the client. Status, docs and automations in one place.</p>'
    + '<pre style="white-space:pre-wrap;background:rgba(0,0,0,.22);padding:12px;border-radius:8px;font-size:13px">' + esc(md) + '</pre>'
    + '<div class="sub">Copy or download the package. Nothing is sent without your yes.</div>'
    + '<button class="g-btn" onclick="navigator.clipboard.writeText(this.previousElementSibling.previousElementSibling.textContent)">Copy package</button>';
  el.innerHTML = html;
  return 'handoff';
}

export default {
  name: 'handoff',
  examples: ['client handoff', 'status for the client', 'handoff package', 'what to hand the client'],
  nearMisses: ['void status', 'system status', 'make a proposal'],
  match(lower, text) { return isHandoff(text); },
  run,
  suite() {
    const ok = isHandoff('client handoff') && isHandoff('status for the client') && !isHandoff('void status');
    return { ok, got: 'match works' };
  }
};
